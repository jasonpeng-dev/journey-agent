export function diagnosticMessage(code: string, fallback: string): string {
  return diagnosticLabels[code] ?? fallback;
}

export function errorText(error: unknown, fallback = "操作失败，请稍后重试。") {
  if (!error || typeof error !== "object") return fallback;
  const code = "code" in error && typeof error.code === "string" ? error.code : null;
  return code ? `${uiLabel(code)}（${code}）` : fallback;
}
