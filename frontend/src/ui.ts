export function uiLabel(value: string | null | undefined): string {
  if (!value) return "—";
  return labels[value] ?? value.replaceAll("_", " ");
}

export function fieldLabel(value: string): string {
  return fieldLabels[value] ?? value.replaceAll("_", " ");
}

export function stepDescription(value: string): string {
  if (value.startsWith("Execute ")) return `执行：${value.slice(8)}`;
  if (value.startsWith("Wait for ")) return `等待结算：${value.slice(9)}`;
  return value;
}

export function resultLabel(value: string | null): string | null {
  if (!value) return null;
  if (value === "Completed") return "已完成";
  return uiLabel(value.toUpperCase().replaceAll(" ", "_"));
}

